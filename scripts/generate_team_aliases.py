def _college_teams(rows: list[tuple[str, ...]]) -> list[dict]:
    """College maps use full school name as code; extras must be globally unique."""

    seen: set[str] = set()
    teams: list[dict] = []
    for row in rows:
        code = row[0]
        aliases = [code]
        if code in seen:
            raise ValueError(f"duplicate college code {code!r}")
        seen.add(code)
        for extra in row[1:]:
            label = str(extra).strip()
            if not label or label in seen:
                continue
            seen.add(label)
            aliases.append(label)
        teams.append({"code": code, "aliases": aliases})
    return teams


def _apply_college_disambig(
    teams: list[dict], disambig: list[tuple[str, ...]]
) -> list[dict]:
    by_code = {t["code"]: t for t in teams}
    seen = {alias for t in teams for alias in t["aliases"]}
    for row in disambig:
        code = row[0]
        target = by_code.get(code)
        if target is None:
            continue
        for extra in row[1:]:
            label = str(extra).strip()
            if not label or label in seen:
                continue
            seen.add(label)
            target["aliases"].append(label)
    return list(by_code.values())


def _write_college(
    name: str,
    package_key: str,
    rows: list[tuple[str, ...]],
    *,
    disambig: list[tuple[str, ...]] | None = None,
    package_aliases: list[str] | None = None,
) -> None:
    teams = _college_teams(rows)
    if disambig:
        teams = _apply_college_disambig(teams, disambig)
    _write(name, package_key, teams, package_aliases=package_aliases)


def _school_names_only(rows: list[tuple[str, ...]]) -> list[tuple[str, ...]]:
    return [(row[0],) for row in rows]


