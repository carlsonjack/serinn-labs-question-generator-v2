ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "config" / "team_aliases"


def _team(code: str, *aliases: str) -> dict:
    names = [code, *aliases]
    return {"code": code, "aliases": list(dict.fromkeys(names))}


def _write(
    name: str,
    package_key: str,
    teams: list[dict],
    *,
    package_aliases: list[str] | None = None,
) -> None:
    payload: dict = {"package_key": package_key, "teams": teams}
    if package_aliases:
        payload["package_aliases"] = package_aliases
    path = OUT / f"{name}.yaml"
    with path.open("w", encoding="utf-8") as handle:
        yaml.safe_dump(payload, handle, sort_keys=False, allow_unicode=True, default_flow_style=False)


def _from_rows(rows: list[tuple]) -> list[dict]:
    return [_team(code, *rest) for code, *rest in rows]


